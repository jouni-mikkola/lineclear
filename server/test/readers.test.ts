// The log readers, on made-up lines in each CLI's exact format (field names and nesting copied from real logs).
import { afterAll, beforeAll, describe, expect, test } from 'bun:test'
import { mkdtempSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { readerFor } from '../server/live/readers/index.ts'
import type { LogEvent } from '../server/live/readers/types.ts'
import { parse, brief, base, ts, cuser, typed, cassistant, toolResult, pimsg, STEPS, S } from './readers-fixture.ts'

describe('claude reader', () => {
  // fails on ebb17d5 too; L20 fixes it
  test.skip('keeps typed prompts and replies; drops meta, wrappers, tool steps and thinking', () => {
    const ev = parse('claude', [
      { type: 'mode', mode: 'normal', sessionId: S },
      { type: 'permission-mode', permissionMode: 'default', sessionId: S },
      cuser('u1', 'Make the button blue', typed),
      cuser('u2', '[Image: original 800x600, displayed at 800x600.]', { isMeta: true }),
      cuser('u3', '<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>', {
        isMeta: true,
      }),
      cuser('u4', '<command-name>/model</command-name>\n            <command-message>model</command-message>\n            <command-args></command-args>'),
      cuser('u5', '<local-command-stdout>Set model to opus</local-command-stdout>'),
      cuser('u6', '<task-notification>\n<task-id>t1</task-id>\n</task-notification>', {
        origin: { kind: 'task-notification', producer: 'session-task' },
        promptSource: 'system',
      }),
      cuser('u7', 'This session is being continued from a previous conversation that ran out of context.', {
        isCompactSummary: true,
        isVisibleInTranscriptOnly: true,
      }),
      cuser('u8', 'subagent prompt', { isSidechain: true }),
      cuser(
        'u9',
        [
          { type: 'text', text: 'Also check the footer' },
          { type: 'text', text: '<system-reminder>\nnote\n</system-reminder>' },
        ],
        typed,
      ),
      cassistant('a1', 'msg_A', { type: 'thinking', thinking: 'hmm', signature: 'sig' }, 'tool_use'),
      cassistant('a2', 'msg_A', { type: 'tool_use', id: 'toolu_1', name: 'Bash', input: { command: 'ls' } }, 'tool_use'),
      toolResult('u10', 'toolu_1', 'src\npackage.json'),
      cassistant('a3', 'msg_B', { type: 'thinking', thinking: 'done', signature: 'sig' }, 'end_turn'),
      cassistant('a4', 'msg_B', { type: 'text', text: 'The button is blue now.' }, 'end_turn'),
      cassistant('a5', 'msg_B', { type: 'text', text: 'The footer looks fine.' }, 'end_turn'),
      { parentUuid: 'a5', ...base, type: 'system', subtype: 'turn_duration', durationMs: 4000, messageCount: 9, timestamp: ts(), uuid: 's1', isMeta: false },
    ])
    expect(brief(ev)).toEqual([
      `session:session-${S}`,
      'user:Make the button blue',
      'user:/model',
      'agent:Set model to opus',
      'user:Also check the footer',
      'agent:The button is blue now.\n\nThe footer looks fine.',
      'turn-end:turn-msg_B',
    ])
    expect(ev[0]).toMatchObject({ kind: 'session', sessionId: S })
    expect(ev.filter((e) => e.kind !== 'usage' && e.kind !== 'turn-start' && !STEPS.has(e.kind))[5].id).toBe('msg_B')
  })

  test('a command Claude Code runs itself reads as typed, with what it printed as its answer, and starts no turn', () => {
    const local = (uuid: string, content: string) => ({
      parentUuid: null,
      ...base,
      version: '2.1.310',
      type: 'system',
      subtype: 'local_command',
      content,
      level: 'info',
      timestamp: ts(),
      uuid,
      isMeta: false,
    })
    const ev = parse('claude', [
      // /clear starts the new session's log
      cuser('u1', '<local-command-caveat>Caveat: The command below was run directly in Claude Code.</local-command-caveat>', { isMeta: true }),
      cuser('u2', '<command-name>/clear</command-name>\n            <command-message>clear</command-message>\n            <command-args></command-args>'),
      local('s1', '<command-name>/context</command-name>\n            <command-message>context</command-message>\n            <command-args></command-args>'),
      local('s2', '<local-command-stdout> \u001b[1mContext Usage\u001b[22m\n\u001b[38;2;136;136;136m⛀ ⛁\u001b[39m 31.5k tokens</local-command-stdout>'),
      local('s3', '<command-name>/model</command-name>\n            <command-message>model</command-message>\n            <command-args>sonnet</command-args>'),
      local('s4', '<local-command-stdout>Set model to Sonnet 5.5</local-command-stdout>'),
      local('s5', '<local-command-stdout></local-command-stdout>'),
      // /compact: as typed, then again in tags under its summary
      cuser('u3', '/compact'),
      cuser('u4', '<command-name>/compact</command-name>\n            <command-message>compact</command-message>\n            <command-args></command-args>'),
      local('s6', '<local-command-stdout>Compacted (ctrl+o to see full summary)</local-command-stdout>'),
    ])
    expect(brief(ev).slice(1)).toEqual([
      'user:/clear',
      'user:/context',
      'agent:```\n Context Usage\n⛀ ⛁ 31.5k tokens\n```',
      'user:/model sonnet',
      'agent:Set model to Sonnet 5.5',
      'user:/compact',
      'agent:Compacted (ctrl+o to see full summary)',
    ])
    expect(ev.some((e) => e.kind === 'turn-start')).toBe(false)
  })

  test('a slash command with arguments, a queued prompt and a long paste read as typed', () => {
    const ev = parse('claude', [
      cuser('u1', '<command-message>review</command-message>\n<command-name>/review</command-name>\n<command-args>the login page</command-args>', typed),
      {
        parentUuid: 'u1',
        ...base,
        attachment: {
          type: 'queued_command',
          prompt: 'and the signup page',
          source_uuid: 'q1',
          delivery_id: 'd1',
          commandMode: 'prompt',
          origin: { kind: 'human' },
          timestamp: ts(),
          humanTurn: true,
        },
        type: 'attachment',
        uuid: 'att1',
        timestamp: ts(),
      },
      {
        parentUuid: 'u1',
        ...base,
        attachment: {
          type: 'queued_command',
          prompt: '<task-notification>x</task-notification>',
          commandMode: 'task-notification',
          origin: { kind: 'task-notification' },
        },
        type: 'attachment',
        uuid: 'att2',
        timestamp: ts(),
      },
      cuser('u2', '<pasted_content id="12">\nline one\nline two\n</pasted_content id="12">', typed),
    ])
    expect(brief(ev).slice(1)).toEqual(['user:/review the login page', 'user:and the signup page', 'user:line one\nline two'])
  })

  test('AskUserQuestion becomes a question, its tool result marks it answered', () => {
    const ev = parse('claude', [
      cuser('u1', 'Pick a colour scheme', typed),
      cassistant('a1', 'msg_Q', { type: 'text', text: 'One question first.' }, 'tool_use'),
      cassistant(
        'a2',
        'msg_Q',
        {
          type: 'tool_use',
          id: 'toolu_Q',
          name: 'AskUserQuestion',
          input: {
            questions: [
              {
                question: 'Which scheme?',
                header: 'Scheme',
                multiSelect: false,
                options: [
                  { label: 'Light', description: 'White background' },
                  { label: 'Dark', description: 'Black background' },
                ],
              },
            ],
          },
        },
        'tool_use',
      ),
      cuser('u2', [{ type: 'tool_result', content: 'Your questions have been answered: "Which scheme?"="Dark".', tool_use_id: 'toolu_Q' }], {
        toolUseResult: { questions: [], answers: { 'Which scheme?': 'Dark' }, annotations: {} },
      }),
    ])
    expect(brief(ev).slice(1)).toEqual(['user:Pick a colour scheme', 'agent:One question first.', 'question:toolu_Q', 'answered:toolu_Q'])
    const q = ev.find((e) => e.kind === 'question')!
    expect(q).toMatchObject({
      tool: 'AskUserQuestion',
      items: [
        {
          header: 'Scheme',
          question: 'Which scheme?',
          multiSelect: false,
          allowCustom: true,
          options: [
            { label: 'Light', description: 'White background' },
            { label: 'Dark', description: 'Black background' },
          ],
        },
      ],
    })
  })

  test('an interrupt ends the turn and is not shown as a prompt', () => {
    const ev = parse('claude', [
      cuser('u1', 'Rewrite everything', typed),
      cassistant('a1', 'msg_I', { type: 'thinking', thinking: '...', signature: 'sig' }, null),
      cuser('u2', [{ type: 'text', text: '[Request interrupted by user]' }]),
    ])
    expect(brief(ev).slice(1)).toEqual(['user:Rewrite everything', 'turn-end:turn-u2'])
  })

  test('a reply split across two reads comes again with the same id and the whole text', () => {
    const r = readerFor('claude')!
    const line = (o: object, i: number) => [{ text: JSON.stringify(o), offset: i }]
    r.parse(line(cuser('u1', 'hi', typed), 0), 'f')
    const a = r.parse(line(cassistant('a1', 'msg_S', { type: 'text', text: 'Part one.' }, 'tool_use'), 1), 'f')
    const b = r.parse(line(cassistant('a2', 'msg_S', { type: 'text', text: 'Part two.' }, 'tool_use'), 2), 'f')
    const said = (ev: LogEvent[]) => ev.filter((e) => e.kind === 'agent')
    expect(said(a)).toMatchObject([{ kind: 'agent', id: 'msg_S', text: 'Part one.' }])
    expect(said(b)).toMatchObject([{ kind: 'agent', id: 'msg_S', text: 'Part one.\n\nPart two.' }])
  })
})

